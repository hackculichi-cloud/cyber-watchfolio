import { test, expect } from '@playwright/test';
import { selectLanguage } from './support/selectLanguage';

test('barbering has its own bilingual identity and an honest school and photo collection', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('/barbering');
  await expect(page.locator('main h1')).toHaveText('Barbering');
  await expect(page).toHaveTitle('Christian Velasco');
  await expect(page.locator('[data-header-brand]')).toHaveAttribute('data-brand-profile', 'barbering');
  await expect(page.locator('[data-header-brand] [data-barber-wordmark]')).toContainText('Culichi');
  await expect(page.locator('[data-footer-mascot]')).toHaveAttribute('data-footer-mascot', 'barbering');
  const art = page.locator('[data-profile-workspace="barbering"] img');
  await expect.poll(() => art.evaluate((image: HTMLImageElement) => image.complete && image.naturalWidth > 0)).toBe(true);
  await expect(page.locator('[data-interactive-mascot], [data-outfit]')).toHaveCount(0);
  const training = page.locator('#training');
  await expect(training).toContainText('Baltra Barbería');
  await expect(training).toContainText('Guadalajara, Jalisco');
  await expect(training).not.toContainText(/Certified|Graduated|Course completed/i);
  const cuts = page.locator('#cuts');
  await expect(cuts).toHaveAttribute('data-empty-collection', 'true');
  await expect(cuts.locator('img, [data-work], .placeholder-image')).toHaveCount(0);
  await expect(page.locator('#tools li')).toHaveCount(4);
  await expect(page.locator('#cv, a[download]')).toHaveCount(0);
  await selectLanguage(page, 'es');
  await expect(page.locator('main h1')).toHaveText('Barbería');
  await expect(cuts.getByRole('heading', { name: 'Mis cortes', exact: true })).toBeVisible();
  await expect(training).toContainText('Escuela principal');
  await expect(page.locator('#tools')).toContainText('Máquina de corte');
  await expect(page.locator('#tools')).toContainText('Máquina de detalle');
  await expect(page).toHaveTitle('Christian Velasco');
  await selectLanguage(page, 'en');
  await expect(page.locator('main h1')).toHaveText('Barbering');
  expect(errors).toEqual([]);
});

test('the barber icon opens its page and only the arrow opens its concise menu', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('/');
  const nav = page.getByRole('navigation', { name: 'Main', exact: true });
  const link = nav.getByRole('link', { name: 'Barbering', exact: true });
  const toggle = nav.getByRole('button', { name: 'Open profile menu: Barbering', exact: true });
  await link.hover();
  await expect(toggle).toHaveAttribute('aria-expanded', 'false');
  await expect(page.locator('[data-header-brand]')).toHaveAttribute('data-brand-profile', 'barbering');
  await expect(page.locator('[data-header-brand] [data-barber-wordmark]')).toBeVisible();
  await toggle.hover();
  const popup = page.getByRole('dialog', { name: 'Specialties: Barbering', exact: true });
  await expect(popup).toBeVisible();
  await expect(popup.getByRole('link')).toHaveCount(3);
  await popup.locator('a[href="/barbering#tools"]').click();
  await expect(page).toHaveURL(/\/barbering#tools$/);
  await expect(page.locator('#tools')).toBeInViewport();
  await expect(popup).not.toBeVisible();
  await page.goto('/');
  await link.click();
  await expect(page).toHaveURL(/\/barbering$/);
  await expect(page.locator('main h1')).toHaveText('Barbering');
});

test('home previews the barber outfit and its own tools and can enter the area', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('/');
  const stage = page.locator('[data-home-mascot]');
  await expect(stage.locator('[data-outfit]')).toHaveCount(7);
  const choice = stage.locator('[data-outfit="barbering"]');
  await choice.focus();
  await expect(stage).toHaveAttribute('data-preview-outfit', 'barbering');
  await expect(page.locator('[data-header-mascot]')).toHaveAttribute('data-header-mascot', 'barbering');
  await expect(stage.locator('[data-tool-field="barbering"] [data-tool-prop="hair-clipper"]')).toBeVisible();
  await expect(stage.locator('[data-tool-field="barbering"] [data-tool-prop="barber-scissors"]')).toBeVisible();
  await expect(page.locator('[data-gear-preview="barbering"]')).toContainText('Hair clipper');
  await expect(page.locator('[data-personal-skills-card="barbering"]')).toContainText('Baltra Barbería');
  await page.keyboard.press('Escape');
  await expect(page.locator('[data-header-mascot]')).toHaveAttribute('data-header-mascot', 'emblem');
  await stage.getByRole('button', { name: 'Greet Culichi and choose an outfit', exact: true }).click();
  await choice.click();
  await expect(page).toHaveURL(/\/barbering$/);
  await expect(page.locator('[data-profile-workspace="barbering"]')).toBeVisible();
});

test('phone visitors open cuts and tools directly without looking below a hidden panel', async ({ browser }) => {
  for (const width of [320, 390]) {
    const context = await browser.newContext({ viewport: { width, height: width === 320 ? 640 : 844 }, isMobile: true, hasTouch: true, reducedMotion: 'reduce' });
    await context.addInitScript(() => localStorage.setItem('portfolio-lang', 'es'));
    const page = await context.newPage();
    await page.goto('/');
    await page.evaluate(() => document.fonts.ready);
    const stage = page.locator('[data-home-mascot]');
    const choice = stage.locator('[data-outfit="barbering"]');
    const box = (await choice.boundingBox())!;
    expect(box.width).toBeGreaterThanOrEqual(44);
    expect(box.height).toBeGreaterThanOrEqual(44);
    expect(box.x).toBeGreaterThanOrEqual(0);
    expect(box.x + box.width).toBeLessThanOrEqual(width);
    const quickNav = (await page.locator('[data-mobile-quicknav]').boundingBox())!;
    expect(box.y + box.height).toBeLessThanOrEqual(quickNav.y);
    await choice.tap();
    await expect(page).toHaveURL(/\/barbering$/);
    await expect(page.locator('main h1')).toHaveText('Barbería');
    await expect(page.locator('[data-mobile-profile-section]:visible')).toHaveCount(1);
    await expect(page.locator('#training')).toBeVisible();
    await page.getByRole('link', { name: 'Ver mis cortes', exact: true }).tap();
    await expect(page).toHaveURL(/\/barbering#cuts$/);
    await expect(page.locator('#cuts')).toBeInViewport();
    await expect(page.locator('#training')).toBeHidden();
    await expect(page.locator('#tools')).toBeHidden();
    const jump = page.getByRole('combobox');
    await jump.selectOption('tools');
    await expect(page.locator('#tools')).toBeInViewport();
    await expect(page.locator('#cuts')).toBeHidden();
    await page.reload();
    await expect(jump).toHaveValue('tools');
    await expect(page.locator('#tools')).toBeVisible();
    await page.getByRole('button', { name: 'Abrir menú', exact: true }).tap();
    await page.locator('#mobile-navigation').getByRole('button', { name: 'Abrir menú de especialidades: Barbería', exact: true }).tap();
    const menu = page.locator('#mobile-specialties-barbering');
    await expect(menu.getByRole('link')).toHaveCount(3);
    await menu.locator('a[href="/barbering#training"]').tap();
    await expect(page.locator('#training')).toBeInViewport();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await context.close();
  }
});
